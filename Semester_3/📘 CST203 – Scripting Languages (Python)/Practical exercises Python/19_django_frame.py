# 19. Create a frame using Django

# Steps to create Django frame:
print("Steps to create Django frame:")
print("1. Install Django: pip install django")
print("2. Create project: django-admin startproject myproject")
print("3. Navigate to project: cd myproject")
print("4. Create app: python manage.py startapp myapp")
print("5. Run server: python manage.py runserver")
print()
print("Django frame is a project structure with apps")
